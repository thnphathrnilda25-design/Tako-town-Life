function stRewardOffer(id) {
  const A = stA(id), arc = stArc(id);
  if (!A.done) return say('เรื่องนี้ยังไม่จบ');
  if (A.reward) return say('คุณรับของที่ระลึกของเรื่องนี้แล้ว');
  const list = (ST_REWARDS[id] && ST_REWARDS[id][A.end]) || [];
  if (!list.length) return say('ยังไม่มีของที่ระลึกสำหรับตอนจบนี้');
  openPanel(`🎁 ของที่ระลึก — ${arc.n}`, () => [
    el('div', { className: 'sub' }, `ตอนจบ: ${stEndName(id, A.end)} · เลือกได้ 1 อย่าง (รับภายหลังได้จากแอป 📖 เรื่องราว)`),
    ...list.map(o => row(o.ic, o.n, o.d, btn('รับ', () => {
      if (A.reward) return;
      A.reward = o.id;
      o.run();
      save();
      toast(`🎁 รับแล้ว: ${o.n}`);
      closePanel();
    }))),
  ]);
}

