// Phase 5 — "ชุดเชื่อมเมือง": three connected life stories, four chapters each, one chapter per
// in-game day. They use existing townsfolk, can be missed for good, and end with a choice that
// changes the town. The old seven-chapter main story in quests.js (Q().story) stays untouched:
// this module owns st.story only.

const ST_VER = 1;
const ST_DAY = [0, 2, 4, 6];        // chapter 1 on the start day, then every other day
const ST_GRACE = 1;                 // one spare day before a chapter is lost

function ST() {
  if (!st.story || typeof st.story !== 'object') st.story = {};
  const S = st.story;
  if (S.v !== ST_VER) S.v = ST_VER;
  if (!S.arc || typeof S.arc !== 'object') S.arc = {};
  if (!Array.isArray(S.mem)) S.mem = [];
  if (!S.perk || typeof S.perk !== 'object') S.perk = {};
  if (!S.world || typeof S.world !== 'object') S.world = {};
  if (S.world.cafe === undefined) S.world.cafe = 0;
  if (S.world.family === undefined) S.world.family = 0;
  if (S.world.workshop === undefined) S.world.workshop = 0;
  if (!S.avail || typeof S.avail !== 'object') S.avail = {};
  return S;
}
function stArc(id) { return ST_ARCS.find(a => a.id === id); }
function stA(id) {
  const S = ST();
  const A = S.arc[id] || (S.arc[id] = {});
  if (!A.start) A.start = 0;
  if (A.ch === undefined) A.ch = 0;
  if (!A.done) A.done = 0;
  if (A.end === undefined) A.end = null;
  if (!A.endDay) A.endDay = 0;
  if (A.reward === undefined) A.reward = null;
  if (!A.pts) A.pts = 0;
  if (!A.missed) A.missed = 0;
  if (!A.last) A.last = 0;
  if (!Array.isArray(A.log)) A.log = [];
  if (!A.flags || typeof A.flags !== 'object') A.flags = {};
  if (A.nudge === undefined) A.nudge = 0;
  return A;
}
