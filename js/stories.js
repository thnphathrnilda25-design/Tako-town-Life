function stCast() {
  // people entries expose age/role/sched as live getters (walk.js), so retune their source
  // fields instead of assigning to the entities themselves.
  const set = (id, age, role) => {
    const base = PEOPLE.find(q => q.id === id), p = stNpc(id);
    if (base) {
      base.born = yearsPassed() - age;
      if (role) base.adultRole = role;
    }
    if (base && p) {
      p._sched = null; p._schedRole = null;
      liveFields(p, base, p.k);          // re-capture born/role for this entity's live getters
    }
  };
  set('finn', 46, 'barista');
  set('ryan', 42, 'shopkeeper');
  set('ivy', 40);
  set('leo', 14, 'student');
  set('cora', 72, 'retiree');
  set('nora', 43);
  const ryan = stNpc('ryan'), ivy = stNpc('ivy'), solo = id => !!st.solo?.[id];
  const taken = id => st.partner === id || st.spouse === id;
  if (ryan && ivy && !solo('ryan') && !solo('ivy') && !taken('ryan') && !taken('ivy')) {
    if (!ryan.mate) ryan.mate = 'ivy';
    if (!ivy.mate) ivy.mate = 'ryan';
  }
}
