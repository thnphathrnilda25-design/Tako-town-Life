function stDue(A) { return A.start + ST_DAY[Math.max(0, Math.min(3, A.ch))]; }
function stReady(A) {
  return !!A.start && !A.done && A.ch < 4 && day() >= stDue(A) && day() <= stDue(A) + ST_GRACE && A.last !== day();
}
function stCanStart(arc) {
  const A = stA(arc.id);
  return !A.start && !A.done && day() >= arc.day && stRel(arc.who) >= arc.rel;
}
