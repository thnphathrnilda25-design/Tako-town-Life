function stArcDetail(id) {
  const arc = stArc(id), A = stA(id);
  const back = btn('◀ เรื่องราวทั้งหมด', () => { stArcSel = null; refreshPanel(); });
  const head = [
    back,
    row(arc.ic, arc.n, `${arc.sub} · ${A.done ? 'จบแล้ว' : A.start ? `บทที่ ${Math.min(4, A.ch + 1)}/4` : 'ยังไม่เริ่ม'}`),
    el('div', { className: 'sub' }, arc.blurb),
  ];
  const next = [];
  if (!A.done) {
    if (!A.start) next.push(el('div', { className: 'sub' }, stCanStart(arc) ? `🔔 พร้อมเริ่มแล้ว — ไปคุยกับ ${stNpc(arc.who)?.n || arc.who} ที่ ${stWhere(arc.who)}` : `🔒 ${stReqText(arc)}`));
    else {
      const withId = ST_CH_WITH[id][Math.min(3, A.ch)];
      next.push(row('📖', `บทที่ ${A.ch + 1} — ${stChTitle(id, A.ch)}`, `ไปหา ${stNpc(withId)?.n || withId} ที่ ${stWhere(withId)}`));
      next.push(el('div', { className: 'sub' }, stArcStatus(arc)));
    }
  }
  const chapters = [];
  for (let i = 0; i < 4; i++) {
    const log = A.log.find(l => l.ch === i + 1);
    let s = '🔒 ยังไม่ถึง';
    if (log) s = log.miss ? '⏳ พลาด — บทนี้ผ่านไปแล้ว' : '✅ ผ่านแล้ว';
    else if (A.start && !A.done && i + 1 === A.ch + 1) s = stReady(A) ? '🔔 พร้อมแล้ว' : day() < stDue(A) ? `📅 วันที่ ${stDue(A)}` : '⌛ เลยกำหนด';
    chapters.push(row(log?.miss ? '⏳' : log ? '✅' : '·', `บทที่ ${i + 1} — ${arc.chapters[i]}`, s));
  }
  const ending = A.done ? [
    el('div', { className: 'sec' }, `บทส่งท้าย — ${stEndName(id, A.end)}`),
    ...(ST_ENDINGS[id][A.end]?.text || []).map(p => el('div', { style: 'line-height:1.5' }, p)),
    row('🎁', A.reward ? 'รับของที่ระลึกแล้ว' : 'ของที่ระลึกจากตอนจบ', A.reward ? '—' : 'เลือกได้ 1 อย่าง', A.reward ? null : btn('รับ', () => stRewardOffer(id))),
  ] : [];
  const mem = ST().mem.filter(m => m.a === id).slice().reverse();
  return [
    ...head, ...next,
    el('div', { className: 'sec' }, 'บท'),
    ...chapters,
    ...ending,
    el('div', { className: 'sec' }, `ความทรงจำจากเรื่องนี้ (${mem.length})`),
    ...(mem.length ? mem.map(m => row('📷', m.t, `วันที่ ${m.d} · ${m.x}`)) : [el('div', { className: 'sub' }, 'ยังไม่มีความทรงจำ — เรื่องนี้เพิ่งเริ่มต้น')]),
  ];
}
