function stArcStatus(arc) {
  const A = stA(arc.id);
  if (A.done) return `✅ จบแล้ว — ${stEndName(arc.id, A.end)}`;
  if (!A.start) return stCanStart(arc) ? `🔔 พร้อมเริ่ม — ไปคุยกับ ${stNpc(arc.who)?.n || arc.who}` : `🔒 ${stReqText(arc)}`;
  const name = stNpc(ST_CH_WITH[arc.id][Math.min(3, A.ch)])?.n || 'ชาวเมือง';
  if (A.last === day()) return `บทที่ ${Math.min(4, A.ch + 1)}/4 · วันนี้คุยแล้ว พรุ่งนี้ต่อ`;
  const due = stDue(A);
  if (day() < due) return `บทที่ ${Math.min(4, A.ch + 1)}/4 · บทต่อไปวันที่ ${due}`;
  if (stReady(A)) return `🔔 บทที่ ${A.ch + 1}/4 พร้อมแล้ว — ไปหา ${name} ที่ ${stWhere(ST_CH_WITH[arc.id][A.ch])}`;
  return `บทที่ ${Math.min(4, A.ch + 1)}/4 · เลยกำหนดแล้ว`;
}
